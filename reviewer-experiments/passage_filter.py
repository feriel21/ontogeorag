import re
JUNK = [
    r"doi\.org", r"\bdoi\b", r"e-?mail", r"corresponding author", r"\btel\b",
    r"marine and petroleum geology", r"geomorphology \d", r"\bvol\.\b",
    r"©", r"all rights reserved", r"\bpp\.\b", r"university", r"department of",
    r"^\s*fig\.", r"written communication",
]
JUNK_RE = re.compile("|".join(JUNK), re.I)
GENERIC_DEF = re.compile(
    r"general term that refers to all|refers to all slumps", re.I)

def is_junk(passage: str) -> bool:
    """True si le passage ressemble a un en-tete/ref/def generique, pas a une phrase geologique."""
    p = passage.strip()
    if len(p) < 40:
        return True
    if GENERIC_DEF.search(p):
        return True
    # densite de marqueurs de metadonnees
    hits = len(JUNK_RE.findall(p))
    return hits >= 2

def both_present(passage: str, source: str, target: str) -> bool:
    """Garde-fou: au moins un mot porteur de source ET de target presents en clair."""
    pl = passage.lower()
    def core(x):
        toks = [t for t in re.sub(r"[^a-z ]"," ",x.lower()).split() if len(t) >= 4]
        return toks[:2] or [x.lower()[:4]]
    s_ok = any(t in pl for t in core(source))
    t_ok = any(t in pl for t in core(target))
    return s_ok and t_ok

if __name__ == "__main__":
    tests = [
        "Mass-transport deposit (MTD) is a general term that refers to all slumps...",
        "doi.org/10.1016 ... Marine and Petroleum Geology 26 (2009) E-mail address",
        "Excess pore pressure generated by rapid sedimentation reduced the shear strength of the slope, triggering failure.",
    ]
    for t in tests:
        print(is_junk(t), "|", t[:60])
